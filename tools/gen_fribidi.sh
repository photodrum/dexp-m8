#!/bin/sh
# Генерирует таблицы fribidi (*.tab.i, fribidi-unicode-version.h, fribidi-config.h) для сборки
# crengine под Android без meson (ROADMAP «План 7.1», шаг 4). Повторяет gen.tab/meson.build.
# Запускать после обновления подмодуля third_party/fribidi; результат коммитится.
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC=$ROOT/third_party/fribidi
OUT=$ROOT/app/src/main/cpp/engines/cre/fribidi
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"

VER=$(sed -n "s/^project('fribidi', 'c', version: '\([0-9.]*\)'.*/\1/p" "$SRC/meson.build")
IFACE=$(sed -n 's/^interface_version = \([0-9]*\)/\1/p' "$SRC/meson.build")
MAJ=${VER%%.*}; REST=${VER#*.}; MIN=${REST%%.*}; MIC=${REST#*.}

# fribidi-config.h — как lib/fribidi-config.h.in; int на armeabi-v7a — 4 байта.
sed -e "s|@configure_input@|generated by tools/gen_fribidi.sh|" \
    -e "s|@PACKAGE@|fribidi|" -e "s|@PACKAGE_NAME@|GNU FriBidi|" \
    -e "s|@PACKAGE_BUGREPORT@|https://github.com/fribidi/fribidi/issues/new|" \
    -e "s|@FRIBIDI_VERSION@|$VER|" -e "s|@FRIBIDI_MAJOR_VERSION@|$MAJ|" \
    -e "s|@FRIBIDI_MINOR_VERSION@|$MIN|" -e "s|@FRIBIDI_MICRO_VERSION@|$MIC|" \
    -e "s|@FRIBIDI_INTERFACE_VERSION@|$IFACE|g" -e "s|@SIZEOF_INT@|4|" \
    -e "s|@FRIBIDI_MSVC_BUILD_PLACEHOLDER@|#undef FRIBIDI_BUILT_WITH_MSVC|" \
    "$SRC/lib/fribidi-config.h.in" > "$OUT/fribidi-config.h"

CF="-UHAVE_CONFIG_H -DHAVE_STRINGIZE -DDONT_HAVE_FRIBIDI_CONFIG_H -DHAVE_STDLIB_H -DHAVE_STRING_H -DHAVE_STRINGS_H -DSTDC_HEADERS=1 -I$SRC/lib -I$TMP"
U=$SRC/gen.tab/unidata
G=$SRC/gen.tab

gcc $CF -o "$TMP/gen-unicode-version" "$G/gen-unicode-version.c"
"$TMP/gen-unicode-version" "$U/ReadMe.txt" "$U/BidiMirroring.txt" gen-unicode-version > "$TMP/fribidi-unicode-version.h"
cp "$TMP/fribidi-unicode-version.h" "$OUT/"

gen() { # имя, входные файлы
    name=$1; shift
    gcc $CF -o "$TMP/gen-$name-tab" "$G/gen-$name-tab.c" "$G/packtab.c"
    "$TMP/gen-$name-tab" 2 "$@" "gen-$name-tab" > "$OUT/$name.tab.i"
}
gen bidi-type "$U/UnicodeData.txt"
gen joining-type "$U/UnicodeData.txt" "$U/ArabicShaping.txt"
gen arabic-shaping "$U/UnicodeData.txt"
gen mirroring "$U/BidiMirroring.txt"
gen brackets "$U/BidiBrackets.txt" "$U/UnicodeData.txt"
gen brackets-type "$U/BidiBrackets.txt"

echo "fribidi $VER -> $OUT"
ls -la "$OUT"
