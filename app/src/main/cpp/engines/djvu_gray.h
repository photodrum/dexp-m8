/*
 * «Усилить контраст скана» (B31) — только для DjVu.
 *
 * Почему не в `cre_gray.h`: `dexp_gray_to_palette()` зовут и crengine (`reader_jni.cpp`),
 * а там контраст делает вёрстка шрифтом. Тумблер B31 относится к сканам, поэтому усиление
 * живёт отдельной функцией и применяется к 8-битному серому **до** сведения к палитре
 * (`dexp_gray_to_palette`): после неё остаётся 16 уровней, и растягивать уже нечего.
 *
 * Кривая — линейное растяжение вокруг середины: y = (x − 128) · 1.6 + 128 с отсечкой
 * по краям. У скана фон обычно 200…240, текст 30…70: растяжение выбеливает фон и
 * чернит штрих, что и нужно E-Ink. Фотографии в книге при этом теряют полутона —
 * поэтому тумблер, а не всегда включено.
 */
#ifndef DEXP_DJVU_GRAY_H
#define DEXP_DJVU_GRAY_H

#include <stddef.h>

/** Усиление в десятых: 16 — 160 %. */
#define DEXP_DJVU_CONTRAST_GAIN 16

/** Растянуть контраст [n] байт серого на месте. */
static inline void dexp_djvu_contrast(unsigned char *g, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        int v = ((int)g[i] - 128) * DEXP_DJVU_CONTRAST_GAIN / 10 + 128;
        if (v < 0) v = 0;
        else if (v > 255) v = 255;
        g[i] = (unsigned char)v;
    }
}

#endif
