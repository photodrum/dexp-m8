package ru.ogrpfsense.dexpm8.chess

// Уровни игры компьютера (п. 25.1в) для экрана 25.2: глубина, предел времени и «неточность».
// Числа — по замеру на книге (25.1г, tools/chess_bench.kt): PX30 в миттельшпиле ~80 узлов/мс
// (хост ~1700); глубина 4 — 0,7–1,3 с, 5 — 4,4–4,7 с, 6 — 15–43 с; в эндшпиле глубина 7 — 4,4 с.
// Предел времени есть у каждого уровня, чтобы на медленной книге ход не затягивался; новая
// итерация после половины предела не начинается — поэтому предел ≈ 2 × время нужной глубины.
// Уровни 1–6: глубина ограничена, ход обычно за доли секунды (предел — на острые позиции);
// 7–8 — только время: в эндшпиле считают глубже, чем в миттельшпиле.

object Level {
    const val COUNT = 8

    private val TABLE = arrayOf(
        Limits(depth = 1, timeMs = 2000, noise = 400),
        Limits(depth = 2, timeMs = 2000, noise = 200),
        Limits(depth = 3, timeMs = 3000, noise = 100),
        Limits(depth = 3, timeMs = 3000, noise = 40),
        Limits(depth = 4, timeMs = 5000, noise = 15),
        Limits(depth = 4, timeMs = 5000),
        Limits(timeMs = 8000),
        Limits(timeMs = 20000),
    )

    /** Пределы уровня [n] = 1…[COUNT] (вне границ — ближайший уровень). */
    fun of(n: Int): Limits = TABLE[n.coerceIn(1, COUNT) - 1]
}
